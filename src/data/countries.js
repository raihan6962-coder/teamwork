export function searchCountries(query) {
  const lower = query.toLowerCase();
  return countries.filter((c) => c.name.toLowerCase().includes(lower) || c.code.toLowerCase().includes(lower));
}

export function getCountryByCode(code) {
  return countries.find((c) => c.code === code);
}

export function getCountryPage(page, perPage) {
  perPage = perPage || 10;
  const start = page * perPage;
  return countries.slice(start, start + perPage);
}

export function getTotalCountryPages(perPage) {
  perPage = perPage || 10;
  return Math.ceil(countries.length / perPage);
}
